import { ru } from "./messages-ru.js";

// Every text that rig shows to a person lives in a catalog: stdout and stderr lines, errors, event texts, status lines.
// `en` is the source. `ru` is typed as `Messages`, so a key missing from it is a type error. A parameterized message is
// a function that returns the whole sentence, so no grammar is built in code. Failures of the store, lock, files,
// processes and settings merge are in the `failure` group: an error text from the operating system or a child process is
// data and goes into such a message as a parameter. tests/message-catalogue-guard.test.ts fails on an English literal
// that builds a failure or a reason outside this file and messages-ru.ts.

export const LANGUAGES = ["en", "ru"] as const;
export type Language = (typeof LANGUAGES)[number];
export const DEFAULT_LANGUAGE: Language = "en";

export const isLanguage = (value: unknown): value is Language => LANGUAGES.some((language) => language === value);

// A language other than the default one: the languages that texts are translated into (feature manifests keep their English text in plain fields).
export type TranslatedLanguage = Exclude<Language, "en">;
export const isTranslatedLanguage = (value: unknown): value is TranslatedLanguage => isLanguage(value) && value !== DEFAULT_LANGUAGE;

